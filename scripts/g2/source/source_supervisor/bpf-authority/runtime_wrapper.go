const runtimeRuncSHA256 = "2bd8eb4735299cf288e306ab240de4e173524195ef17f83baff3ec2175ebecd1"
const runtimeShimRoot = "/run/g2-docker/runtime-runc/moby"
const runtimeInputLimit = 4 << 20

// runtimeArgs contains selection information only. The broker independently
// validates the observed task, bundle, grant and, for exec, process template.
type runtimeArgs struct {
	Command, ContainerID, BundlePath, ProcessPath, PidFile string
}

func runtimePath(s string) bool {
	return len(s) > 1 && len(s) <= 4096 && filepath.IsAbs(s) && filepath.Clean(s) == s && !strings.ContainsRune(s, 0)
}

func runtimeContainerID(s string) bool {
	if len(s) != 64 {
		return false
	}
	for _, c := range s {
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f') {
			return false
		}
	}
	return true
}

// parseRuntimeArgs accepts the arguments following argv[0]. The sole root is
// the one generated by the pinned Docker and containerd configuration.
func parseRuntimeArgs(args []string) (runtimeArgs, error) {
	var out runtimeArgs
	if len(args) == 1 && args[0] == "features" {
		out.Command = "features"
		return out, nil
	}
	if len(args) < 8 || args[0] != "--root" || args[1] != runtimeShimRoot || args[2] != "--log" || !runtimePath(args[3]) || args[4] != "--log-format" || args[5] != "json" {
		return out, errGuardProtocol
	}
	logPath := args[3]
	if filepath.Base(logPath) != "log.json" {
		return out, errGuardProtocol
	}
	bundle := filepath.Dir(logPath)
	out.Command = args[6]
	args = args[7:]
	if len(args) == 0 {
		return runtimeArgs{}, errGuardProtocol
	}
	var positional []string
	seen := make(map[string]bool)
	for i := 0; i < len(args); i++ {
		arg := args[i]
		if strings.HasPrefix(arg, "-") {
			if len(positional) != 0 {
				return runtimeArgs{}, errGuardProtocol
			}
			if seen[arg] {
				return runtimeArgs{}, errGuardProtocol
			}
			seen[arg] = true
			switch arg {
			case "--bundle", "--pid-file", "--process":
				if i+1 >= len(args) || !runtimePath(args[i+1]) {
					return runtimeArgs{}, errGuardProtocol
				}
				i++
				value := args[i]
				switch arg {
				case "--bundle":
					if out.Command != "create" || value != bundle {
						return runtimeArgs{}, errGuardProtocol
					}
					out.BundlePath = value
				case "--process":
					base := filepath.Base(value)
					suffix := strings.TrimPrefix(base, "runc-process")
					if out.Command != "exec" || filepath.Dir(value) != "/tmp" || suffix == base || suffix == "" {
						return runtimeArgs{}, errGuardProtocol
					}
					for _, c := range suffix {
						if c < '0' || c > '9' {
							return runtimeArgs{}, errGuardProtocol
						}
					}
					out.ProcessPath = value
				case "--pid-file":
					if filepath.Dir(value) != bundle {
						return runtimeArgs{}, errGuardProtocol
					}
					base := filepath.Base(value)
					if out.Command == "create" {
						if base != "init.pid" {
							return runtimeArgs{}, errGuardProtocol
						}
					} else if out.Command == "exec" {
						if !strings.HasSuffix(base, ".pid") || !runtimeContainerID(strings.TrimSuffix(base, ".pid")) {
							return runtimeArgs{}, errGuardProtocol
						}
					} else {
						return runtimeArgs{}, errGuardProtocol
					}
					out.PidFile = value
				}
			case "--detach":
				if out.Command != "exec" {
					return runtimeArgs{}, errGuardProtocol
				}
			case "--force":
				if out.Command != "delete" {
					return runtimeArgs{}, errGuardProtocol
				}
			case "--all":
				if out.Command != "kill" {
					return runtimeArgs{}, errGuardProtocol
				}
			default:
				return runtimeArgs{}, errGuardProtocol
			}
		} else {
			positional = append(positional, arg)
		}
	}
	if len(positional) == 0 || !runtimeContainerID(positional[0]) {
		return runtimeArgs{}, errGuardProtocol
	}
	out.ContainerID = positional[0]
	if filepath.Base(bundle) != out.ContainerID {
		return runtimeArgs{}, errGuardProtocol
	}
	switch out.Command {
	case "create":
		if len(positional) != 1 || out.BundlePath == "" || !seen["--pid-file"] {
			return runtimeArgs{}, errGuardProtocol
		}
	case "exec":
		if len(positional) != 1 || out.ProcessPath == "" || !seen["--pid-file"] || !seen["--detach"] {
			return runtimeArgs{}, errGuardProtocol
		}
	case "start", "state", "delete":
		if len(positional) != 1 {
			return runtimeArgs{}, errGuardProtocol
		}
	case "kill":
		if len(positional) != 2 {
			return runtimeArgs{}, errGuardProtocol
		}
		sig, err := strconv.Atoi(positional[1])
		if err != nil || (sig != int(unix.SIGTERM) && sig != int(unix.SIGKILL)) || strconv.Itoa(sig) != positional[1] {
			return runtimeArgs{}, errGuardProtocol
		}
	default:
		return runtimeArgs{}, errGuardProtocol
	}
	return out, nil
}

// runtimeDirectory holds each checked component while traversing. A root-owned
// sticky /tmp is permitted only for go-runc's root-owned exec process file.
func runtimeDirectory(name string, stickyTmp bool) (int, error) {
	if !runtimePath(name) {
		return -1, errGuardProtocol
	}
	fd, err := unix.Open("/", unix.O_PATH|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		return -1, err
	}
	var root unix.Stat_t
	if unix.Fstat(fd, &root) != nil || root.Uid != 0 || root.Gid != 0 || root.Mode&0022 != 0 {
		_ = unix.Close(fd)
		return -1, errGuardProtocol
	}
	for _, part := range strings.Split(strings.TrimPrefix(name, "/"), "/") {
		next, e := unix.Openat2(fd, part, &unix.OpenHow{Flags: unix.O_PATH | unix.O_DIRECTORY | unix.O_NOFOLLOW | unix.O_CLOEXEC, Resolve: unix.RESOLVE_BENEATH | unix.RESOLVE_NO_SYMLINKS | unix.RESOLVE_NO_MAGICLINKS})
		if e != nil {
			_ = unix.Close(fd)
			return -1, e
		}
		var held, named unix.Stat_t
		e = unix.Fstat(next, &held)
		if e == nil {
			e = unix.Fstatat(fd, part, &named, unix.AT_SYMLINK_NOFOLLOW)
		}
		allowSticky := stickyTmp && name == "/tmp" && part == "tmp" && held.Mode&unix.S_ISVTX != 0
		if e != nil || held.Uid != 0 || held.Gid != 0 || held.Mode&unix.S_IFMT != unix.S_IFDIR || (held.Mode&0022 != 0 && !allowSticky) || !sameTrustedStat(held, named) {
			_ = unix.Close(next)
			_ = unix.Close(fd)
			return -1, errGuardProtocol
		}
		_ = unix.Close(fd)
		fd = next
	}
	return fd, nil
}

func runtimeHeldFile(dir int, name string) (*os.File, string, error) {
	return runtimeHeldFileWithDiagnostic(dir, name, nil)
}

func runtimeHeldFileWithDiagnostic(dir int, name string, d *runtimeInputDiagnostic) (*os.File, string, error) {
	if name == "" || filepath.Base(name) != name {
		d.reject(ownerProbeStageWrapperPrepareFileName)
		return nil, "", errGuardProtocol
	}
	fd, err := unix.Openat2(dir, name, &unix.OpenHow{Flags: unix.O_RDONLY | unix.O_NOFOLLOW | unix.O_CLOEXEC, Resolve: unix.RESOLVE_BENEATH | unix.RESOLVE_NO_SYMLINKS | unix.RESOLVE_NO_MAGICLINKS})
	if err != nil {
		d.reject(ownerProbeStageWrapperPrepareFileOpen)
		return nil, "", err
	}
	file := os.NewFile(uintptr(fd), name)
	if file == nil {
		d.reject(ownerProbeStageWrapperPrepareFileNewFile)
		_ = unix.Close(fd)
		return nil, "", errGuardProtocol
	}
	var before, after, named unix.Stat_t
	if unix.Fstat(fd, &before) != nil {
		d.reject(ownerProbeStageWrapperPrepareFileStat)
		_ = file.Close()
		return nil, "", errGuardProtocol
	}
	if stage := runtimeHeldFileMetadataStage(before); stage != 0 {
		d.reject(stage)
		_ = file.Close()
		return nil, "", errGuardProtocol
	}
	h := sha256.New()
	n, err := io.Copy(h, io.LimitReader(file, runtimeInputLimit+1))
	if err != nil {
		d.reject(ownerProbeStageWrapperPrepareFileRead)
		_ = file.Close()
		return nil, "", errGuardProtocol
	}
	if n != before.Size {
		d.reject(ownerProbeStageWrapperPrepareFileCount)
		_ = file.Close()
		return nil, "", errGuardProtocol
	}
	if unix.Fstat(fd, &after) != nil {
		d.reject(ownerProbeStageWrapperPrepareFileHeldStat)
		_ = file.Close()
		return nil, "", errGuardProtocol
	}
	if unix.Fstatat(dir, name, &named, unix.AT_SYMLINK_NOFOLLOW) != nil {
		d.reject(ownerProbeStageWrapperPrepareFileNamedStat)
		_ = file.Close()
		return nil, "", errGuardProtocol
	}
	if difference := trustedStatDifference(before, after); difference != runtimeStatSame {
		d.rejectDifference(ownerProbeStageWrapperPrepareFileHeldDev, difference)
		_ = file.Close()
		return nil, "", errGuardProtocol
	}
	if difference := trustedStatDifference(before, named); difference != runtimeStatSame {
		d.rejectDifference(ownerProbeStageWrapperPrepareFileNamedDev, difference)
		_ = file.Close()
		return nil, "", errGuardProtocol
	}
	if _, err = file.Seek(0, io.SeekStart); err != nil {
		d.reject(ownerProbeStageWrapperPrepareFileSeek)
		_ = file.Close()
		return nil, "", err
	}
	return file, hex.EncodeToString(h.Sum(nil)), nil
}

// prepareContainerSelftestBundle changes only the fixed probe's default OCI
// seccomp profile. The broker independently authenticates its grant and the
// complete resulting bundle before the wrapper can execute runc.
func prepareContainerSelftestBundle(dir int, dirName, leaf string, d *runtimeInputDiagnostic) error {
	held, digest, err := runtimeHeldFileWithDiagnostic(dir, leaf, d)
	if err != nil {
		return err
	}
	defer held.Close()
	var before unix.Stat_t
	if unix.Fstat(int(held.Fd()), &before) != nil {
		d.reject(ownerProbeStageWrapperPrepareHeldStat)
		return errGuardProtocol
	}
	raw, err := readHeldRegularWithDiagnostic(int(held.Fd()), runtimeInputLimit, d)
	if err != nil {
		return errGuardProtocol
	}
	if hashBytes(raw) != digest {
		d.reject(ownerProbeStageWrapperPrepareHash)
		return errGuardProtocol
	}
	value, err := runtimeJSON(raw)
	if err != nil {
		d.reject(ownerProbeStageWrapperPrepareJSON)
		return err
	}
	process, ok := value["process"].(map[string]any)
	if !ok {
		d.reject(ownerProbeStageWrapperPrepareProcess)
		return errGuardProtocol
	}
	args, ok := process["args"].([]any)
	if !ok || len(args) != 3 || args[0] != "/opt/g2/g2-container-bpf-probe" || args[1] != "selftest" || args[2] != "container-raw-denial" {
		return nil
	}
	var spec specs.Spec
	if err = json.Unmarshal(raw, &spec); err != nil || spec.Process == nil || spec.Linux == nil || spec.Root == nil || !spec.Root.Readonly || spec.Process.User.UID != 10002 || spec.Process.User.GID != 10002 || !spec.Process.NoNewPrivileges {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return errGuardProtocol
	}
	caps := spec.Process.Capabilities
	if caps != nil && (len(caps.Bounding) != 0 || len(caps.Effective) != 0 || len(caps.Permitted) != 0 || len(caps.Inheritable) != 0 || len(caps.Ambient) != 0) {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return errGuardProtocol
	}
	profile, err := seccomp.GetDefaultProfile(&spec)
	if err != nil || profile == nil || !reflect.DeepEqual(spec.Linux.Seccomp, profile) {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return errGuardProtocol
	}
	if err = allowContainerSelftestBPF(profile); err != nil {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return err
	}
	profileRaw, err := json.Marshal(profile)
	if err != nil {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return err
	}
	profileValue, err := runtimeJSON(profileRaw)
	if err != nil {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return err
	}
	linux, ok := value["linux"].(map[string]any)
	if !ok {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return errGuardProtocol
	}
	linux["seccomp"] = profileValue
	rewritten, err := json.Marshal(value)
	if err != nil || len(rewritten) == 0 || len(rewritten) > runtimeInputLimit {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return errGuardProtocol
	}
	if err = runtimeRecheckInput(dir, dirName, leaf, held, digest, before, false); err != nil {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return err
	}
	fd, err := unix.Openat2(dir, leaf, &unix.OpenHow{Flags: unix.O_RDWR | unix.O_NOFOLLOW | unix.O_CLOEXEC, Resolve: unix.RESOLVE_BENEATH | unix.RESOLVE_NO_SYMLINKS | unix.RESOLVE_NO_MAGICLINKS})
	if err != nil {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return err
	}
	defer unix.Close(fd)
	var writable unix.Stat_t
	if unix.Fstat(fd, &writable) != nil || !sameTrustedStat(before, writable) {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return errGuardProtocol
	}
	for offset := 0; offset < len(rewritten); {
		n, writeErr := unix.Pwrite(fd, rewritten[offset:], int64(offset))
		if writeErr != nil {
			d.reject(ownerProbeStageWrapperPrepareSelftest)
			return writeErr
		}
		if n <= 0 {
			d.reject(ownerProbeStageWrapperPrepareSelftest)
			return errGuardProtocol
		}
		offset += n
	}
	if err = unix.Ftruncate(fd, int64(len(rewritten))); err != nil {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return err
	}
	if err = unix.Fsync(fd); err != nil {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return err
	}
	checked, actualHash, err := runtimeHeldFile(dir, leaf)
	if err != nil {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return err
	}
	defer checked.Close()
	var actual unix.Stat_t
	if unix.Fstat(int(checked.Fd()), &actual) != nil || actual.Dev != before.Dev || actual.Ino != before.Ino || actualHash != hashBytes(rewritten) {
		d.reject(ownerProbeStageWrapperPrepareSelftest)
		return errGuardProtocol
	}
	return nil
}

// Reopen the named parent and leaf to detect replacement or mutation across
// the broker exchange. The broker separately validates the same held objects.
func runtimeRecheckInput(dir int, dirName, leaf string, file *os.File, expected string, saved unix.Stat_t, sticky bool) error {
	namedDir, err := runtimeDirectory(dirName, sticky)
	if err != nil {
		return err
	}
	defer unix.Close(namedDir)
	var oldDir, newDir unix.Stat_t
	if unix.Fstat(dir, &oldDir) != nil || unix.Fstat(namedDir, &newDir) != nil || oldDir.Dev != newDir.Dev || oldDir.Ino != newDir.Ino || oldDir.Mode != newDir.Mode || oldDir.Uid != newDir.Uid || oldDir.Gid != newDir.Gid {
		return errGuardProtocol
	}
	var original, reopened unix.Stat_t
	if unix.Fstat(int(file.Fd()), &original) != nil {
		return errGuardProtocol
	}
	check, digest, err := runtimeHeldFile(namedDir, leaf)
	if err != nil {
		return err
	}
	defer check.Close()
	if unix.Fstat(int(check.Fd()), &reopened) != nil || !sameTrustedStat(saved, original) || !sameTrustedStat(original, reopened) || digest != expected {
		return errGuardProtocol
	}
	return nil
}

func runtimeListener() (int, error) {
	var sizes [6]byte
	_, _, errno := unix.Syscall(unix.SYS_SECCOMP, unix.SECCOMP_GET_NOTIF_SIZES, 0, uintptr(unsafe.Pointer(&sizes[0])))
	if errno != 0 || binary.LittleEndian.Uint16(sizes[0:2]) != 80 || binary.LittleEndian.Uint16(sizes[2:4]) != 24 || binary.LittleEndian.Uint16(sizes[4:6]) != 64 {
		return -1, errGuardProtocol
	}
	listener, err := installRuntimeListener()
	if err != nil {
		return -1, err
	}
	probe := make([]byte, 24)
	binary.LittleEndian.PutUint32(probe[8:12], unix.SECCOMP_ADDFD_FLAG_SEND)
	binary.LittleEndian.PutUint32(probe[12:16], uint32(listener))
	binary.LittleEndian.PutUint32(probe[20:24], unix.O_CLOEXEC)
	_, err = notificationIOCTL(listener, unix.SECCOMP_IOCTL_NOTIF_ADDFD, probe)
	if err != unix.ENOENT {
		_ = unix.Close(listener)
		return -1, errGuardProtocol
	}
	return listener, nil
}

func bindRuntime(fd, brokerPIDFD int, boot string, parsed runtimeArgs, bundleHash, processHash any, fds []int, deadline time.Time) error {
	var container any
	if parsed.Command != "features" {
		container = parsed.ContainerID
	}
	request := map[string]any{"version": json.Number("1"), "boot_id": boot, "request_id": json.Number("1"), "operation": "BIND_RUNTIME", "body": map[string]any{"container_id": container, "command": parsed.Command, "bundle_sha256": bundleHash, "process_sha256": processHash}}
	raw, err := canonicalControl(request)
	if err != nil {
		return err
	}
	if err = waitFD(fd, unix.POLLOUT, deadline); err != nil {
		return err
	}
	if err = sendControl(fd, raw, fds); err != nil {
		return err
	}
	if err = waitFD(fd, unix.POLLIN, deadline); err != nil {
		return err
	}
	response, cred, _, err := receiveControl(fd, 0)
	if err != nil {
		return err
	}
	peer, err := unix.GetsockoptUcred(fd, unix.SOL_SOCKET, unix.SO_PEERCRED)
	if err != nil || cred == nil || peer.Pid != cred.Pid || peer.Uid != cred.Uid || peer.Gid != cred.Gid || cred.Uid != 0 || cred.Gid != 0 || !livePIDFD(brokerPIDFD) {
		return errGuardProtocol
	}
	ack, err := parseCanonicalControl(response)
	if err != nil {
		return err
	}
	if !exactKeys(ack, "version", "boot_id", "epoch", "run_token", "principal_id", "request_id", "request_sha256", "status", "body") || ack["version"] != json.Number("1") || ack["boot_id"] != boot || ack["run_token"] != authorityRunToken || ack["request_id"] != json.Number("1") || ack["status"] != "OK" {
		return errControlFrame
	}
	sum := sha256.Sum256(raw)
	if ack["request_sha256"] != hex.EncodeToString(sum[:]) {
		return errControlFrame
	}
	if id, ok := exactNumber(ack["principal_id"]); !ok || id == 0 {
		return errControlFrame
	}
	epoch, ok := ack["epoch"].(string)
	if !ok || len(epoch) != 32 || epoch == strings.Repeat("0", 32) {
		return errControlFrame
	}
	for _, c := range epoch {
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f') {
			return errControlFrame
		}
	}
	body, ok := ack["body"].(map[string]any)
	if !ok || !exactKeys(body, "invocation_id", "task_cookie", "grant_id", "generation", "config_sha256", "exec_id") {
		return errControlFrame
	}
	for _, k := range []string{"invocation_id", "task_cookie", "generation"} {
		v, ok := exactNumber(body[k])
		if !ok || v == 0 {
			return errControlFrame
		}
	}
	if parsed.Command == "features" {
		if body["grant_id"] != nil || body["config_sha256"] != nil || body["exec_id"] != nil {
			return errControlFrame
		}
	} else {
		id, ok := exactNumber(body["grant_id"])
		if !ok || id == 0 {
			return errControlFrame
		}
		if _, ok := digestString(body["config_sha256"]); !ok {
			return errControlFrame
		}
		if parsed.Command == "exec" {
			id, ok = exactNumber(body["exec_id"])
			if !ok || id == 0 {
				return errControlFrame
			}
		} else if body["exec_id"] != nil {
			return errControlFrame
		}
	}
	if time.Until(deadline) <= 0 || !livePIDFD(brokerPIDFD) {
		return errGuardProtocol
	}
	return nil
}

// execRuntime executes the held package file itself, retaining the caller's
// argv, environment and already-inherited descriptors. All wrapper-created
// descriptors use CLOEXEC; the listener is closed locally before this call.
func execRuntime(fd int, argv, env []string) error {
	argp, err := syscall.SlicePtrFromStrings(argv)
	if err != nil {
		return err
	}
	envp, err := syscall.SlicePtrFromStrings(env)
	if err != nil {
		return err
	}
	empty := []byte{0}
	_, _, errno := unix.Syscall6(unix.SYS_EXECVEAT, uintptr(fd), uintptr(unsafe.Pointer(&empty[0])), uintptr(unsafe.Pointer(&argp[0])), uintptr(unsafe.Pointer(&envp[0])), unix.AT_EMPTY_PATH, 0)
	runtime.KeepAlive(argp)
	runtime.KeepAlive(envp)
	runtime.KeepAlive(empty)
	if errno != 0 {
		return errno
	}
	return errGuardProtocol
}

func runRuntimeWrapper(args []string) (ownerProbeRuntimeStage, error) {
	deadline, err := guestDeadline(60 * time.Second)
	if err != nil {
		return ownerProbeStageWrapperDeadline, err
	}
	runtime.LockOSThread()
	if unix.Gettid() != os.Getpid() || os.Geteuid() != 0 || os.Getegid() != 0 || len(os.Args) == 0 || os.Args[0] != "/opt/g2/g2-bpf-runtime" {
		return ownerProbeStageWrapperIdentity, errGuardProtocol
	}
	parsed, err := parseRuntimeArgs(args)
	if err != nil {
		return ownerProbeStageWrapperArgs, err
	}
	program, hash, err := openTrustedRegular("/usr/bin/runc", 128<<20)
	if err != nil {
		return ownerProbeStageWrapperRuncOpen, err
	}
	defer program.Close()
	if hash != runtimeRuncSHA256 {
		return ownerProbeStageWrapperRuncIdentity, errGuardProtocol
	}
	var programStat unix.Stat_t
	var magic [4]byte
	if unix.Fstat(int(program.Fd()), &programStat) != nil || programStat.Mode&0111 == 0 {
		return ownerProbeStageWrapperRuncIdentity, errGuardProtocol
	}
	if n, e := program.ReadAt(magic[:], 0); e != nil || n != len(magic) || magic != [4]byte{0x7f, 'E', 'L', 'F'} {
		return ownerProbeStageWrapperRuncIdentity, errGuardProtocol
	}
	boot, err := fixedBootID()
	if err != nil {
		return ownerProbeStageWrapperBootID, err
	}
	var bundleHash, processHash any
	var rights []int
	inputDir := -1
	var held *os.File
	var inputName, inputDirectory string
	var inputStat unix.Stat_t
	sticky := false
	if parsed.Command == "create" {
		inputDirectory, inputName = parsed.BundlePath, "config.json"
		inputDir, err = runtimeDirectory(inputDirectory, false)
		if err != nil {
			return ownerProbeStageWrapperInputDir, err
		}
		defer unix.Close(inputDir)
		var prepareDiagnostic runtimeInputDiagnostic
		if err = prepareContainerSelftestBundle(inputDir, inputDirectory, inputName, &prepareDiagnostic); err != nil {
			stage := prepareDiagnostic.stage
			if stage == 0 {
				stage = ownerProbeStageWrapperBundlePrepare
			}
			return stage, err
		}
		held, hash, err = runtimeHeldFile(inputDir, inputName)
		if err != nil {
			return ownerProbeStageWrapperInputFile, err
		}
		defer held.Close()
		bundleHash = hash
	} else if parsed.Command == "exec" {
		inputDirectory, inputName, sticky = "/tmp", filepath.Base(parsed.ProcessPath), true
		inputDir, err = runtimeDirectory(inputDirectory, true)
		if err != nil {
			return ownerProbeStageWrapperInputDir, err
		}
		defer unix.Close(inputDir)
		held, hash, err = runtimeHeldFile(inputDir, inputName)
		if err != nil {
			return ownerProbeStageWrapperInputFile, err
		}
		defer held.Close()
		processHash = hash
	}
	if held != nil {
		if unix.Fstat(int(held.Fd()), &inputStat) != nil || (sticky && inputStat.Mode&07777 != 0600) {
			return ownerProbeStageWrapperInputStat, errGuardProtocol
		}
		if err = runtimeRecheckInput(inputDir, inputDirectory, inputName, held, hash, inputStat, sticky); err != nil {
			return ownerProbeStageWrapperInputBeforeBind, err
		}
	}
	control, brokerPIDFD, err := connectBroker(boot, deadline)
	if err != nil {
		return ownerProbeStageWrapperConnect, err
	}
	defer func() {
		if control >= 0 {
			_ = unix.Close(control)
		}
	}()
	defer unix.Close(brokerPIDFD)
	listener := -1
	if parsed.Command != "features" {
		listener, err = runtimeListener()
		if err != nil {
			return ownerProbeStageWrapperListener, fmt.Errorf("BPF_AUTH_UNAVAILABLE: listener: %w", err)
		}
		defer func() {
			if listener >= 0 {
				_ = unix.Close(listener)
			}
		}()
		rights = append(rights, listener)
		if parsed.Command == "create" {
			rights = append(rights, inputDir, int(held.Fd()))
		}
		if parsed.Command == "exec" {
			rights = append(rights, int(held.Fd()))
		}
	}
	if err = bindRuntime(control, brokerPIDFD, boot, parsed, bundleHash, processHash, rights, deadline); err != nil {
		return ownerProbeStageWrapperBind, err
	}
	if held != nil {
		if err = runtimeRecheckInput(inputDir, inputDirectory, inputName, held, hash, inputStat, sticky); err != nil {
			return ownerProbeStageWrapperInputAfterBind, err
		}
	}
	checkProgram, checkHash, err := openTrustedRegular("/usr/bin/runc", 128<<20)
	if err != nil {
		return ownerProbeStageWrapperRuncReopen, err
	}
	var originalProgram, namedProgram unix.Stat_t
	if unix.Fstat(int(program.Fd()), &originalProgram) != nil || unix.Fstat(int(checkProgram.Fd()), &namedProgram) != nil || !sameTrustedStat(programStat, originalProgram) || !sameTrustedStat(originalProgram, namedProgram) || checkHash != runtimeRuncSHA256 {
		_ = checkProgram.Close()
		return ownerProbeStageWrapperRuncRecheck, errGuardProtocol
	}
	if err = checkProgram.Close(); err != nil {
		return ownerProbeStageWrapperRuncCheckClose, err
	}
	if listener >= 0 {
		if err = unix.Close(listener); err != nil {
			return ownerProbeStageWrapperListenerClose, err
		}
		listener = -1
	}
	if err = unix.Close(control); err != nil {
		return ownerProbeStageWrapperControlClose, err
	}
	control = -1
	if time.Until(deadline) <= 0 || !livePIDFD(brokerPIDFD) {
		return ownerProbeStageWrapperPreExecLive, unix.ETIMEDOUT
	}
	argv := append([]string{os.Args[0]}, args...)
	return ownerProbeStageWrapperExecReturn, execRuntime(int(program.Fd()), argv, os.Environ())
}
