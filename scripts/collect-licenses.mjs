import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const toolchain = `go${readFileSync(join(root, 'go.mod'), 'utf8').match(/^go (\S+)$/m)[1]}`
const go = (...args) => execFileSync('go', args, { cwd: root, encoding: 'utf8', env: { ...process.env, GOTOOLCHAIN: toolchain } }).trim()
const noticeName = /^(?:licen[cs]e|copying|notice|copyright)(?:[._-].*)?$/i
const sections = []
function append(component, path, base = root) {
  const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').trimEnd()
  sections.push(`\n${'='.repeat(78)}\n${component}\nFile: ${relative(base, path)}\n${'='.repeat(78)}\n\n${text}\n`)
}
function notices(directory, recursive) {
  const found = []
  for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const path = join(directory, entry.name)
    if (entry.isFile() && noticeName.test(entry.name)) found.push(path)
    else if (recursive && entry.isDirectory() && !entry.name.startsWith('.') && entry.name !== 'node_modules') found.push(...notices(path, true))
  }
  return found
}
function component(name, directory, recursive = false) {
  const files = notices(directory, recursive)
  if (files.length === 0) throw new Error(`Missing license/notice text: ${name}`)
  for (const file of files) append(name, file, directory)
}

append('Houfeng — AGPL-3.0-only; original code licensed by its owner; no warranty', join(root, 'LICENSE'))
component(`Go runtime and standard library — ${go('env', 'GOVERSION')}`, go('env', 'GOROOT'))
const requirements = JSON.parse(go('mod', 'edit', '-json')).Require
for (const requirement of requirements.sort((a, b) => a.Path.localeCompare(b.Path, 'en'))) {
  const module = JSON.parse(go('list', '-m', '-json', requirement.Path))
  if (module.Version !== requirement.Version || module.Replace || !module.Dir) throw new Error(`Unresolved or replaced dependency: ${requirement.Path}`)
  component(`${module.Path}@${module.Version}`, module.Dir, true)
}
const lock = JSON.parse(readFileSync(join(root, 'web/package-lock.json'), 'utf8'))
for (const [path, pkg] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  if (!path || pkg.dev) continue
  const directory = join(root, 'web', path)
  const installed = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'))
  if (installed.version !== pkg.version) throw new Error(`Installed version differs from lock: ${path}`)
  component(`${installed.name}@${pkg.version} — ${pkg.license ?? 'see license text'}`, directory)
}
append('IBM Plex fonts — SIL Open Font License 1.1', join(root, 'web/public/fonts/OFL.txt'))
append('xykt/IPQuality — pinned modified detector; AGPL-3.0', join(root, 'agent/ipquality/detector_assets/LICENSE'))
append('xykt/IPQuality provenance and modifications', join(root, 'agent/ipquality/detector_assets/MODIFICATIONS.md'))
const output = 'Houfeng license and third-party notices\n\nGenerated by: node scripts/collect-licenses.mjs\nDependency versions: go.mod and web/package-lock.json.\nLicense wording is retained per component, including nested upstream notices;\nline endings and trailing whitespace are normalized.\nThis conservative inventory is not a claim that every upstream file is shipped.\nThird-party components retain their own licenses; Houfeng licensing does not replace them.\nContainer OS package notices remain under /usr/share/doc in the image.\n' + sections.join('')
const destination = join(root, 'web/public/licenses.txt')
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('License bundle is stale; run node scripts/collect-licenses.mjs')
  console.log(`License bundle matches ${sections.length} notice texts`)
} else {
  writeFileSync(destination, output)
  console.log(`Wrote ${sections.length} notice texts to web/public/licenses.txt`)
}
