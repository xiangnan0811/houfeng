// These temporary one-column probes exercise the validated production CHECK
// expression and column nullability only. They do not exercise production
// triggers, foreign keys, full-row constraints, birth, or deletion issuance.
func newRecordIdentityCheckProbe(
	t *testing.T, ctx context.Context, tx pgx.Tx, surface recordIdentitySurface, marker, expectedType string,
) (pgx.Tx, string, string) {
	t.Helper()
	probe, err := tx.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := probe.Rollback(ctx); err != nil {
			t.Errorf("rollback identity check probe: %v", err)
		}
	})

	var constraintName, expression, columnType, collation string
	var notNull bool
	var matches int64
	err = probe.QueryRow(ctx, `select c.conname::text, pg_catalog.pg_get_expr(c.conbin, c.conrelid),
	  pg_catalog.format_type(a.atttypid, a.atttypmod), a.attnotnull,
	  case when a.attcollation = 0 then ''
	    else pg_catalog.format('%I.%I', collation_namespace.nspname, co.collname) end,
	  count(*) over ()
	  from pg_catalog.pg_constraint c
	  join pg_catalog.pg_attribute a on a.attrelid = c.conrelid and a.attname = $2
	  left join pg_catalog.pg_collation co on co.oid = a.attcollation
	  left join pg_catalog.pg_namespace collation_namespace on collation_namespace.oid = co.collnamespace
	  where c.conrelid = pg_catalog.to_regclass('public.' || $1) and c.contype = 'c'
	    and c.conkey = array[a.attnum]::smallint[] and c.convalidated and c.conislocal
	    and a.attnum > 0 and not a.attisdropped
	    and strpos(pg_catalog.pg_get_expr(c.conbin, c.conrelid), $3) > 0`,
		surface.table, surface.column, marker).Scan(&constraintName, &expression, &columnType, &notNull, &collation, &matches)
	if err != nil || matches != 1 {
		t.Fatalf("locate validated identity check for %s.%s: matched %d, %v", surface.table, surface.column, matches, err)
	}
	if columnType != expectedType || notNull != !surface.nullable {
		t.Fatalf("identity column %s.%s has type %s and not-null %t; want %s and not-null %t",
			surface.table, surface.column, columnType, notNull, expectedType, !surface.nullable)
	}
	column := pgx.Identifier{surface.column}.Sanitize()
	definition := column + " " + columnType
	if collation != "" {
		definition += " collate " + collation
	}
	if notNull {
		definition += " not null"
	}
	definition += ", constraint " + pgx.Identifier{constraintName}.Sanitize() + " check (" + expression + ")"
	if _, err := probe.Exec(ctx, "create temp table record_identity_check_probe ("+definition+") on commit drop"); err != nil {
		t.Fatalf("create identity check probe for %s.%s: %v", surface.table, surface.column, err)
	}
	return probe, "insert into pg_temp.record_identity_check_probe (" + column + ") values ($1)", constraintName
}

func assertRecordIdentityCheckValue(t *testing.T, ctx context.Context, probe pgx.Tx, insert, constraintName string, value any, valid bool) {
	t.Helper()
	sp, err := probe.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	_, err = sp.Exec(ctx, insert, value)
	if rollbackErr := sp.Rollback(ctx); rollbackErr != nil {
		t.Fatalf("rollback identity check value %v: %v", value, rollbackErr)
	}
	if valid {
		if err != nil {
			t.Errorf("identity check rejected %v: %v", value, err)
		}
		return
	}
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) || pgErr.Code != "23514" || pgErr.ConstraintName != constraintName {
		t.Errorf("invalid identity %v: %v; want 23514 from %s", value, err, constraintName)
	}
}

func assertRecordIdentityNullability(t *testing.T, ctx context.Context, probe pgx.Tx, insert string, surface recordIdentitySurface) {
	t.Helper()
	sp, err := probe.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	_, err = sp.Exec(ctx, insert, nil)
	if rollbackErr := sp.Rollback(ctx); rollbackErr != nil {
		t.Fatalf("rollback null identity: %v", rollbackErr)
	}
	if surface.nullable {
		if err != nil {
			t.Errorf("nullable identity rejected NULL: %v", err)
		}
		return
	}
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) || pgErr.Code != "23502" || pgErr.ColumnName != surface.column {
		t.Errorf("non-null identity accepted NULL: %v; want 23502 on %s", err, surface.column)
	}
}

func assertRecordIdentityCheck(t *testing.T, ctx context.Context, tx pgx.Tx, surface recordIdentitySurface) {
	t.Helper()
	t.Run(surface.name, func(t *testing.T) {
		probe, insert, constraintName := newRecordIdentityCheckProbe(t, ctx, tx, surface, "rec2_", "text")
		for _, id := range recordIdentityValidExamples {
			assertRecordIdentityCheckValue(t, ctx, probe, insert, constraintName, id, true)
		}
		for _, id := range recordIdentityInvalidExamples {
			assertRecordIdentityCheckValue(t, ctx, probe, insert, constraintName, id, false)
		}
		assertRecordIdentityNullability(t, ctx, probe, insert, surface)
	})
}

func assertRecordIdentitySetInserts(t *testing.T, ctx context.Context, tx pgx.Tx) {
	t.Helper()
	for _, table := range []string{"comparison_client_workbenches", "comparison_client_save_attempts"} {
		t.Run(table+"_source_set", func(t *testing.T) {
			surface := recordIdentitySurface{table, table, "source_record_ids", false}
			probe, insert, constraintName := newRecordIdentityCheckProbe(t, ctx, tx, surface, "record_text_set_is_canonical", "text[]")
			for _, tc := range []struct {
				ids   []string
				valid bool
			}{
				{[]string{recordIdentityValidExamples[0]}, true},
				{[]string{recordIdentityValidExamples[1]}, true},
				{[]string{recordIdentityValidExamples[2]}, true},
				{[]string{recordIdentityValidExamples[1], recordIdentityValidExamples[2], recordIdentityValidExamples[0]}, true},
				{[]string{recordIdentityValidExamples[0], recordIdentityValidExamples[1]}, false},
				{[]string{recordIdentityValidExamples[0], recordIdentityValidExamples[0]}, false},
				{[]string{recordIdentityInvalidExamples[3]}, false},
			} {
				assertRecordIdentityCheckValue(t, ctx, probe, insert, constraintName, tc.ids, tc.valid)
			}
			assertRecordIdentityNullability(t, ctx, probe, insert, surface)
		})
	}
}

