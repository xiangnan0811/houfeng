// This exercises the command parser only; it does not issue a deletion.
func assertRecordIdentityIssuerParser(t *testing.T, ctx context.Context, tx pgx.Tx) {
	t.Helper()
	for _, id := range append(append([]string(nil), recordIdentityValidExamples...), recordIdentityInvalidExamples...) {
		valid := false
		for _, example := range recordIdentityValidExamples {
			valid = valid || id == example
		}
		sp, err := tx.Begin(ctx)
		if err != nil {
			t.Fatal(err)
		}
		_, err = sp.Exec(ctx, `select record_platform_internal.record_deletion_issuer_command(convert_to(json_build_object('record_id', $1::text)::text, 'UTF8'), array['record_id'])`, id)
		if rollbackErr := sp.Rollback(ctx); rollbackErr != nil {
			t.Fatal(rollbackErr)
		}
		if valid && err != nil {
			t.Errorf("issuer parser rejected valid record %q: %v", id, err)
		}
		if !valid {
			var pgErr *pgconn.PgError
			if !errors.As(err, &pgErr) || pgErr.Code != "22023" {
				t.Errorf("issuer parser accepted invalid record %q: %v", id, err)
			}
		}
	}
}

func assertRecordIdentityDeliveryCommand(t *testing.T, ctx context.Context, runtime *pgxpool.Pool) {
	t.Helper()
	command := map[string]any{
		"outbox_row_id": 1, "owner_id": "worker", "owner_generation": 1,
		"owner_expires_at": "2099-01-01T00:00:00Z", "event_expires_at": "2099-01-01T00:00:00Z",
		"project_id": "default", "event_kind": "record_notification_delivery", "subject_kind": "delivery",
		"delivery_id": "rnd_identity", "notification_id": "rnt_" + strings.Repeat("a", 64),
		"recipient_user_id": "usr_missing", "channel": "telegram", "binding_id": "binding",
		"source_version": 1, "authorization_epoch": 1, "record_fence_epoch": 0,
		"expected_state": "pending", "expected_attempt_count": 0,
	}
	for _, id := range append(append([]string(nil), recordIdentityValidExamples...), recordIdentityInvalidExamples...) {
		command["record_id"] = id
		body, err := json.Marshal(command)
		if err != nil {
			t.Fatal(err)
		}
		_, err = runtime.Exec(ctx, `select * from public.record_external_delivery_start($1::bytea)`, body)
		valid := false
		for _, example := range recordIdentityValidExamples {
			valid = valid || id == example
		}
		var pgErr *pgconn.PgError
		want := "22023"
		if valid {
			// A well-formed request reaches the genuine missing-recipient fence.
			want = "55000"
		}
		if !errors.As(err, &pgErr) || pgErr.Code != want {
			t.Errorf("delivery record %q: %v, want %s", id, err, want)
		}
	}

	delete(command, "expected_state")
	delete(command, "expected_attempt_count")
	command["attempt_no"] = 1
	command["started_at"] = "2025-01-01T00:00:00Z"
	command["attempt_id"] = "rna_" + strings.Repeat("0", 64)
	command["outcome"] = "sent"
	command["retry_after_us"] = 0
	for _, id := range append(append([]string(nil), recordIdentityValidExamples...), recordIdentityInvalidExamples...) {
		command["record_id"] = id
		body, err := json.Marshal(command)
		if err != nil {
			t.Fatal(err)
		}
		_, err = runtime.Exec(ctx, `select * from public.record_external_delivery_outcome($1::bytea)`, body)
		valid := false
		for _, example := range recordIdentityValidExamples {
			valid = valid || id == example
		}
		wantMessage := "invalid external delivery outcome identity"
		if valid {
			// The record passed the terminal identity check; the deliberately
			// wrong attempt ID is rejected by the next independent check.
			wantMessage = "invalid external delivery attempt identity"
		}
		var pgErr *pgconn.PgError
		if !errors.As(err, &pgErr) || pgErr.Code != "22023" || pgErr.Message != wantMessage {
			t.Errorf("terminal delivery record %q: %v, want %q", id, err, wantMessage)
		}
	}
}
