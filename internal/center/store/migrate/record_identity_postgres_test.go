func TestPostgresIntegrationRecordIdentitySchema(t *testing.T) {
	t.Run("upgrade_and_inserts", func(t *testing.T) {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
		defer cancel()
		profile := appACLCurrentReleasedPostgresProfile(t, appACLCurrentP80Migration)
		fixture := newExactAppACLCurrentSuccessorPostgresFixture(t, ctx)
		db := fixture.openRolePool(t, ctx, fixture.migratorRole)
		seedAppACLCurrentReleasedGenesis(t, ctx, fixture, db, profile)

		if _, err := db.Exec(ctx, `insert into public.records
		  (record_id, lock_version, authorization_epoch, created_at, updated_at)
		  values ('rec_preserved', 7, 3, '2025-01-01T00:00:00Z', '2025-01-02T00:00:00Z')`); err != nil {
			t.Fatalf("seed predecessor record: %v", err)
		}
		if _, err := db.Exec(ctx, `insert into public.record_origins (origin_id, origin_kind, origin_digest, source_record_id)
		  values ('ror_preserved', 'import', decode(repeat('ab',32),'hex'), 'rec_preserved')`); err != nil {
			t.Fatalf("seed predecessor origin: %v", err)
		}
		if _, err := db.Exec(ctx, `insert into public.record_import_jobs
		  (import_job_id,actor_id,idempotency_key,job_state,identity_classification,archive_digest,expires_at)
		  values ('rij_predecessor','usr_predecessor','predecessor-import','quarantined','unknown',decode(repeat('a1',32),'hex'),now()+interval '1 hour')`); err != nil {
			t.Fatalf("seed predecessor import job: %v", err)
		}
		if _, err := db.Exec(ctx, `insert into public.record_import_plans
		  (import_plan_id,import_job_id,plan_digest,object_count,remap_count,expires_at)
		  values ('rip_predecessor','rij_predecessor',decode(repeat('b2',32),'hex'),2,2,now()+interval '1 hour')`); err != nil {
			t.Fatalf("seed predecessor import plan: %v", err)
		}
		if _, err := db.Exec(ctx, `insert into public.record_import_entity_mappings
		  (import_plan_id,entity_kind,source_id,source_identity_digest,target_id)
		  values ('rip_predecessor','record','rec_oldsource',decode(repeat('c3',32),'hex'),'rec_oldtarget'),
		         ('rip_predecessor','attachment','att_oldsource',decode(repeat('d4',32),'hex'),'att_oldtarget')`); err != nil {
			t.Fatalf("seed predecessor import mappings: %v", err)
		}
		var beforeMappings string
		if err := db.QueryRow(ctx, `select jsonb_agg(to_jsonb(m) order by entity_kind)::text
		  from public.record_import_entity_mappings m where import_plan_id='rip_predecessor'`).Scan(&beforeMappings); err != nil {
			t.Fatalf("read predecessor import mappings: %v", err)
		}
		before := readIdentityPredecessorRecord(t, ctx, db)
		beforeOrigin := readIdentityPredecessorOrigin(t, ctx, db)
		// Renaming the actual predecessor check proves the migration does not
		// rely on PostgreSQL's autogenerated constraint name.
		oldName := findIdentityPredecessorCheck(t, ctx, db)
		if _, err := db.Exec(ctx, `alter table public.records rename constraint `+pgx.Identifier{oldName}.Sanitize()+` to identity_renamed_predecessor`); err != nil {
			t.Fatalf("rename predecessor check: %v", err)
		}
		manifest, err := ConvergeAppACLCurrent(ctx, db, fixture.runtimeRole, fixture.adminRole, fixture.deletionWorkerRole)
		if err != nil {
			t.Fatalf("upgrade predecessor identity checks: %v", err)
		}
		if after := readIdentityPredecessorRecord(t, ctx, db); after != before {
			t.Fatalf("upgrade changed existing record: before %s, after %s", before, after)
		}
		if after := readIdentityPredecessorOrigin(t, ctx, db); after != beforeOrigin {
			t.Fatalf("upgrade changed existing origin or digest: before %s, after %s", beforeOrigin, after)
		}
		var afterMappings string
		var mappingsRemainUnbound bool
		if err := db.QueryRow(ctx, `select jsonb_agg(to_jsonb(m)-'birth_allocation_id'-'owner_target_record_id' order by entity_kind)::text,
		  count(*)=2 and bool_and(birth_allocation_id is null and owner_target_record_id is null)
		  from public.record_import_entity_mappings m where import_plan_id='rip_predecessor'`).Scan(&afterMappings, &mappingsRemainUnbound); err != nil || afterMappings != beforeMappings || !mappingsRemainUnbound {
			t.Fatalf("predecessor mappings changed or gained birth authority: %v", err)
		}
		repeated, err := ConvergeAppACLCurrent(ctx, db, fixture.runtimeRole, fixture.adminRole, fixture.deletionWorkerRole)
		if err != nil || repeated.ManifestDigest != manifest.ManifestDigest {
			t.Fatalf("repeat current convergence: %v", err)
		}

		assertRecordIdentityCatalog(t, ctx, db)
		tx, err := db.Begin(ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer func() { _ = tx.Rollback(ctx) }()
		for _, surface := range recordIdentityCheckSurfaces() {
			assertRecordIdentityCheck(t, ctx, tx, surface)
		}
		assertRecordIdentitySetInserts(t, ctx, tx)
		assertRecordIdentityCanonicalSets(t, ctx, tx)
		assertRecordIdentityIssuerParser(t, ctx, tx)
		assertRecordIdentityNonRecordInputs(t, ctx, tx)
		runtime := fixture.openRolePool(t, ctx, fixture.runtimeRole)
		assertRecordIdentityDeliveryCommand(t, ctx, runtime)
	})

	t.Run("reject_unexpected_predecessor_check", func(t *testing.T) {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
		defer cancel()
		profile := appACLCurrentReleasedPostgresProfile(t, appACLCurrentP80Migration)
		fixture := newExactAppACLCurrentSuccessorPostgresFixture(t, ctx)
		db := fixture.openRolePool(t, ctx, fixture.migratorRole)
		seedAppACLCurrentReleasedGenesis(t, ctx, fixture, db, profile)
		if _, err := db.Exec(ctx, `insert into public.records (record_id) values ('rec_preserved')`); err != nil {
			t.Fatal(err)
		}
		before := readIdentityPredecessorRecord(t, ctx, db)
		oldName := findIdentityPredecessorCheck(t, ctx, db)
		if _, err := db.Exec(ctx, `alter table public.records drop constraint `+pgx.Identifier{oldName}.Sanitize()); err != nil {
			t.Fatal(err)
		}
		if _, err := db.Exec(ctx, `alter table public.records add constraint identity_drift_check
		  check (record_id ~ '^rec_[a-z0-9]{1,64}$' or record_id = 'foreign')`); err != nil {
			t.Fatal(err)
		}
		_, err := ConvergeAppACLCurrent(ctx, db, fixture.runtimeRole, fixture.adminRole, fixture.deletionWorkerRole)
		if err == nil || !strings.Contains(err.Error(), "unexpected predecessor record identity check") {
			t.Fatalf("upgrade accepted altered predecessor check: %v", err)
		}
		var gateExists, driftExists bool
		if err := db.QueryRow(ctx, `select to_regclass('public.record_deletion_gates') is not null,
		  exists (select 1 from pg_catalog.pg_constraint where conrelid = 'public.records'::regclass and conname = 'identity_drift_check')`).Scan(&gateExists, &driftExists); err != nil {
			t.Fatal(err)
		}
		if gateExists || !driftExists || readIdentityPredecessorRecord(t, ctx, db) != before {
			t.Fatal("rejected upgrade did not preserve predecessor schema and data")
		}
	})
}

func readIdentityPredecessorRecord(t *testing.T, ctx context.Context, db *pgxpool.Pool) string {
	t.Helper()
	var value string
	err := db.QueryRow(ctx, `select row_to_json(r)::text from (
	  select record_id, project_id, lifecycle, current_revision_id, lock_version,
	    authorization_epoch, archived_at, created_at, updated_at
	  from public.records where record_id = 'rec_preserved') r`).Scan(&value)
	if err != nil {
		t.Fatalf("read predecessor record: %v", err)
	}
	return value
}

func readIdentityPredecessorOrigin(t *testing.T, ctx context.Context, db *pgxpool.Pool) string {
	t.Helper()
	var value string
	err := db.QueryRow(ctx, `select row_to_json(r)::text from (
	  select origin_id, project_id, origin_kind, encode(origin_digest, 'hex') as origin_digest,
	    source_deployment_id, source_record_id, created_at
	  from public.record_origins where origin_id = 'ror_preserved') r`).Scan(&value)
	if err != nil {
		t.Fatalf("read predecessor origin: %v", err)
	}
	return value
}

func findIdentityPredecessorCheck(t *testing.T, ctx context.Context, db *pgxpool.Pool) string {
	t.Helper()
	var names []string
	err := db.QueryRow(ctx, `select coalesce(array_agg(c.conname::text order by c.conname), '{}')
	  from pg_catalog.pg_constraint c join pg_catalog.pg_attribute a
	    on a.attrelid = c.conrelid and a.attname = 'record_id'
	  where c.conrelid = 'public.records'::regclass and c.contype = 'c'
	    and c.conkey = array[a.attnum]::smallint[]
	    and pg_catalog.pg_get_expr(c.conbin, c.conrelid) =
	      '(record_id ~ ''^rec_[a-z0-9]{1,64}$''::text)'`).Scan(&names)
	if err != nil || len(names) != 1 {
		t.Fatalf("find actual predecessor record check: %v, %v", names, err)
	}
	return names[0]
}

